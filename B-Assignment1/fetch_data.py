"""Download and cache the DOSM datasets for STISK2023 Assignment 1.

Do not edit this file. Import it from your solution:

    from fetch_data import load_all
    data = load_all()
    income_records = data["hh_income_state"]
    poverty_records = data["hh_poverty_state"]

The first call downloads each dataset from the data.gov.my open API and saves
a copy in data/raw/. Later calls read that saved copy, so your results do not
change if DOSM revises the data after you start. Submit data/raw/ with your work.

You can also run this file directly to download both datasets:

    python fetch_data.py
"""

import json
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

API_URL = "https://api.data.gov.my/data-catalogue/"
DATASETS = ("hh_income_state", "hh_poverty_state")
DATA_DIR = Path(__file__).resolve().parent / "data" / "raw"


def fetch_dataset(dataset_id: str, data_dir: Path = DATA_DIR, refresh: bool = False) -> list[dict]:
    """Return the records of one dataset, downloading them only if no saved copy exists."""
    cache_path = Path(data_dir) / f"{dataset_id}.json"
    if cache_path.exists() and not refresh:
        return json.loads(cache_path.read_text(encoding="utf-8"))["records"]

    url = API_URL + "?" + urllib.parse.urlencode({"id": dataset_id})
    request = urllib.request.Request(url, headers={"User-Agent": "STISK2023-assignment1"})
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            records = json.load(response)
    except (urllib.error.URLError, TimeoutError) as error:
        raise RuntimeError(
            f"Could not download '{dataset_id}' from {url}. Check your connection and try again. "
            "If the API is unavailable, copy the fallback files from the LMS into data/raw/ "
            "and state this in your README."
        ) from error

    payload = {
        "dataset_id": dataset_id,
        "source_url": url,
        "retrieved_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "record_count": len(records),
        "records": records,
    }
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    cache_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    return records


def load_all(data_dir: Path = DATA_DIR, refresh: bool = False) -> dict[str, list[dict]]:
    """Return {dataset_id: records} for every dataset used in Assignment 1."""
    return {dataset_id: fetch_dataset(dataset_id, data_dir, refresh) for dataset_id in DATASETS}


if __name__ == "__main__":
    for dataset_id, records in load_all().items():
        print(f"{dataset_id}: {len(records)} records saved in {DATA_DIR / (dataset_id + '.json')}")


